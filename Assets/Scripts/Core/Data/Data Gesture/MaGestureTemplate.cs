    private List<Vector2> AverageStroke(params List<Vector2>[] strokes)
    {
        int count = 0;
        foreach (var stroke in strokes)
        {
            count = Mathf.Max(count, stroke.Count);
        }

        var averaged = new List<Vector2>(count);

        for (int i = 0; i < count; i++)
        {
            Vector2 sum = Vector2.zero;
            for (int j = 0; j < strokes.Length; j++)
            {
                var stroke = strokes[j];
                Vector2 point = i < stroke.Count ? stroke[i] : stroke[stroke.Count - 1];
                sum += point;
            }

            averaged.Add(sum / strokes.Length);
        }

        return averaged;
    }
