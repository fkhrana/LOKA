    private List<Vector2> AverageStroke(List<Vector2> first, List<Vector2> second, List<Vector2> third, List<Vector2> fourth)
    {
        int count = Mathf.Max(first.Count, Mathf.Max(second.Count, Mathf.Max(third.Count, fourth.Count)));
        var averaged = new List<Vector2>(count);

        for (int i = 0; i < count; i++)
        {
            Vector2 firstPoint = i < first.Count ? first[i] : first[first.Count - 1];
            Vector2 secondPoint = i < second.Count ? second[i] : second[second.Count - 1];
            Vector2 thirdPoint = i < third.Count ? third[i] : third[third.Count - 1];
            Vector2 fourthPoint = i < fourth.Count ? fourth[i] : fourth[fourth.Count - 1];
            averaged.Add((firstPoint + secondPoint + thirdPoint + fourthPoint) / 4f);
        }

        return averaged;
    }
